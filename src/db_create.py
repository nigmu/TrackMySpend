import sys
from pathlib import Path

import psycopg

# Allow `python src/db_create.py` from repo root
_SRC = Path(__file__).resolve().parent
if str(_SRC) not in sys.path:
    sys.path.insert(0, str(_SRC))

from global_configs import DATABASE_URL

# PostgreSQL DDL — keep in sync with DB/schema.dbml
# Declared FKs only where DBML Refs exist: ingest→accounts, parse.stg1→ingest, txn.stg2→parse.
# email_account_id on email_parse_queue_staging and transactions has no FK (denormalized copy).
SCHEMA_STATEMENTS = [
    """
CREATE TABLE IF NOT EXISTS email_accounts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_address TEXT NOT NULL UNIQUE,
    oauth_access_token TEXT NOT NULL,
    oauth_refresh_token TEXT NOT NULL,
    polling_interval_min INTEGER NOT NULL DEFAULT 60,
    last_polled_at TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TEXT NOT NULL,
    last_history_id TEXT
)
    """,
    """
CREATE TABLE IF NOT EXISTS email_ingest_staging (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_account_id INTEGER NOT NULL REFERENCES email_accounts(id) ON DELETE CASCADE,
    email_address TEXT NOT NULL,
    gmail_message_id TEXT NOT NULL,
    thread_id TEXT,
    from_header TEXT,
    to_header TEXT,
    subject TEXT,
    date_header TEXT,
    internal_date_ms TEXT,
    gmail_received_at_utc TEXT,
    date_header_iso TEXT,
    snippet TEXT,
    fetched_at TEXT NOT NULL,
    raw_json TEXT,
    stage2_status TEXT,
    UNIQUE (email_account_id, gmail_message_id)
)
    """,
    """
CREATE INDEX IF NOT EXISTS idx_email_ingest_staging_account
    ON email_ingest_staging (email_account_id, fetched_at)
    """,
    """
CREATE INDEX IF NOT EXISTS idx_ingestion_stage2_status_id
    ON email_ingest_staging (stage2_status, id)
    """,
    """
CREATE TABLE IF NOT EXISTS email_parse_queue_staging (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stg1_id INTEGER NOT NULL REFERENCES email_ingest_staging(id) ON DELETE CASCADE,
    email_account_id INTEGER NOT NULL,
    email_address TEXT NOT NULL,
    gmail_message_id TEXT NOT NULL,
    thread_id TEXT,
    from_header TEXT,
    to_header TEXT,
    subject TEXT,
    date_header TEXT,
    internal_date_ms TEXT,
    gmail_received_at_utc TEXT,
    date_header_iso TEXT,
    snippet TEXT,
    matched_pattern TEXT NOT NULL,
    fetched_at TEXT NOT NULL,
    matched_at TEXT NOT NULL,
    raw_json TEXT,
    parse_status TEXT,
    UNIQUE (email_account_id, gmail_message_id)
)
    """,
    """
CREATE INDEX IF NOT EXISTS idx_email_parse_queue_staging_account
    ON email_parse_queue_staging (email_account_id, matched_at)
    """,
    """
CREATE TABLE IF NOT EXISTS transactions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stg2_id INTEGER NOT NULL REFERENCES email_parse_queue_staging(id) ON DELETE CASCADE,
    email_account_id INTEGER NOT NULL,
    gmail_message_id TEXT NOT NULL,
    parsed_at BIGINT NOT NULL,
    bank TEXT,
    txn_type TEXT,
    type TEXT,
    instrument TEXT,
    channel TEXT,
    amount NUMERIC(18, 4),
    account INTEGER,
    counterparty TEXT,
    counterparty_vpa TEXT,
    reference_number TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT
)
    """,
]


def create_db() -> None:
    conn = psycopg.connect(DATABASE_URL)
    try:
        conn.autocommit = True
        info = conn.info
        print(
            "Connected: "
            f"dbname={info.dbname!r} host={info.host!r} port={info.port} user={info.user!r}"
        )
        with conn.cursor() as cur:
            for stmt in SCHEMA_STATEMENTS:
                cur.execute(stmt.strip())
            cur.execute(
                """
                SELECT tablename
                FROM pg_catalog.pg_tables
                WHERE schemaname = 'public'
                ORDER BY tablename
                """
            )
            tables = [row[0] for row in cur.fetchall()]
        print("Tables in schema public:", ", ".join(tables) if tables else "(none)")
    finally:
        conn.close()


if __name__ == "__main__":
    create_db()
