"""Database schema, applied by migrate.py in order.

Two independent pipelines, easy to tell apart by table prefix:
  - Mail:  email_accounts, sender_filters, raw_mail_data, transactions, sync_runs
           (raw_mail_data -> transactions is a one-to-one, populated by src/mail/parse.py)
  - SMS:   raw_sms_data
           (no transactions link yet — SMS is stored raw; parsing it into
           transactions is the priority next step for this project, not yet built)
  - Shared: app_event_logs (used by both pipelines + TMS Companion OTA)
"""

SCHEMA_STATEMENTS: list[str] = [
    """
    CREATE TABLE IF NOT EXISTS email_accounts (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        email_address TEXT NOT NULL UNIQUE,
        oauth_access_token TEXT NOT NULL,
        oauth_refresh_token TEXT NOT NULL,
        is_active BOOLEAN NOT NULL DEFAULT TRUE,
        polling_interval_min INTEGER NOT NULL DEFAULT 15,
        last_polled_at TIMESTAMPTZ,
        last_history_id BIGINT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS sender_filters (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        pattern TEXT NOT NULL UNIQUE,
        is_active BOOLEAN NOT NULL DEFAULT TRUE,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS raw_mail_data (
        id BIGSERIAL PRIMARY KEY,
        email_account_id INTEGER NOT NULL
            REFERENCES email_accounts (id) ON DELETE CASCADE,
        gmail_message_id TEXT NOT NULL UNIQUE,
        gmail_thread_id TEXT,
        sender TEXT,
        subject TEXT,
        snippet TEXT,
        email_sent_at TIMESTAMPTZ,
        gmail_received_at TIMESTAMPTZ,
        matched_filter_rule TEXT,
        processing_status TEXT NOT NULL DEFAULT 'pending',
        error_message TEXT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_raw_mail_data_status_id
        ON raw_mail_data (processing_status, id)
    """,
    """
    -- Mail-only for now: raw_mail_id is NOT NULL, so every row must come
    -- from an email. There is no raw_sms_id column; SMS is not parsed yet.
    CREATE TABLE IF NOT EXISTS transactions (
        id BIGSERIAL PRIMARY KEY,
        raw_mail_id BIGINT NOT NULL UNIQUE
            REFERENCES raw_mail_data (id) ON DELETE CASCADE,
        amount_paisa BIGINT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS sync_runs (
        id BIGSERIAL PRIMARY KEY,
        account_id INTEGER REFERENCES email_accounts (id) ON DELETE SET NULL,
        trigger TEXT NOT NULL,
        started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        finished_at TIMESTAMPTZ,
        status TEXT NOT NULL DEFAULT 'running',
        messages_seen INTEGER NOT NULL DEFAULT 0,
        inserted INTEGER NOT NULL DEFAULT 0,
        skipped INTEGER NOT NULL DEFAULT 0,
        failed INTEGER NOT NULL DEFAULT 0,
        error_message TEXT
    )
    """,
    """
    -- SMS pipeline (src/sms). Stored as received; no transactions link yet.
    -- content_hash (added below) dedupes on sender+body+device_id (not received_at).
    CREATE TABLE IF NOT EXISTS raw_sms_data (
        id BIGSERIAL PRIMARY KEY,
        sender TEXT,
        body TEXT NOT NULL,
        received_at TIMESTAMPTZ,
        device_id TEXT,
        processing_status TEXT NOT NULL DEFAULT 'pending',
        error_message TEXT,
        content_hash TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS app_event_logs (
        id BIGSERIAL PRIMARY KEY,
        event_type TEXT NOT NULL,
        source TEXT NOT NULL,
        severity TEXT NOT NULL DEFAULT 'info',
        message TEXT NOT NULL,
        context JSONB NOT NULL DEFAULT '{}'::jsonb,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_app_event_logs_created_at
        ON app_event_logs (created_at DESC, id DESC)
    """,
]

# One-time compatibility: old test-server table `raw_sms` -> `raw_sms_data`.
# Split into two halves by migrate.py: statement [0] (the rename) must run
# BEFORE `CREATE TABLE IF NOT EXISTS raw_sms_data` above, otherwise the CREATE
# would win the race and silently strand any old `raw_sms` data. Statements
# [1:] (column adds, hash backfill, NOT NULL, unique index) must run AFTER,
# once the table is guaranteed to exist. Safe to delete this whole list once
# every deployment has migrated past the old `raw_sms` table name.
POST_SCHEMA_STATEMENTS: list[str] = [
    """
    DO $$
    BEGIN
        IF to_regclass('public.raw_sms') IS NOT NULL
           AND to_regclass('public.raw_sms_data') IS NULL THEN
            ALTER TABLE raw_sms RENAME TO raw_sms_data;
        END IF;
    END $$
    """,
    """
    ALTER TABLE raw_sms_data
        ADD COLUMN IF NOT EXISTS processing_status TEXT NOT NULL DEFAULT 'pending'
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_raw_sms_data_status_id
        ON raw_sms_data (processing_status, id)
    """,
    """
    ALTER TABLE raw_sms_data
        ADD COLUMN IF NOT EXISTS error_message TEXT
    """,
    """
    ALTER TABLE raw_sms_data
        ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    """,
    """
    ALTER TABLE raw_sms_data
        ADD COLUMN IF NOT EXISTS content_hash TEXT
    """,
    """
    UPDATE raw_sms_data
    SET content_hash = md5(
        COALESCE(sender, '') || E'\\n' ||
        body || E'\\n' ||
        COALESCE(device_id, '')
    )
    WHERE content_hash IS NULL
    """,
    """
    ALTER TABLE raw_sms_data
        ALTER COLUMN content_hash SET NOT NULL
    """,
    """
    CREATE UNIQUE INDEX IF NOT EXISTS idx_raw_sms_data_content_hash
        ON raw_sms_data (content_hash)
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_raw_sms_data_received_at
        ON raw_sms_data (received_at DESC NULLS LAST)
    """,
]
